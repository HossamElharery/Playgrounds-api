/** Local-only integration audit. Creates and removes its own disposable fixtures. */
require('dotenv').config({ quiet: true });
require('reflect-metadata');
const assert = require('node:assert/strict');
const { PrismaClient } = require('@prisma/client');
const { JwtService } = require('@nestjs/jwt');
const { ConfigService } = require('@nestjs/config');
const { AuthService } = require('../dist/src/modules/auth/auth.service');
const { AuthGuard } = require('../dist/src/common/guards/auth.guard');
const { Reflector } = require('@nestjs/core');
const bcrypt = require('bcrypt');
const db = new URL(process.env.DATABASE_URL);
if (!['localhost', '127.0.0.1', '::1'].includes(db.hostname)) throw new Error('Local test database required');
const prisma = new PrismaClient();
const created = [];
const prefix = `guest-qa-${Date.now()}`;
let squad;
const delivered = new Map();
const service = new AuthService(prisma, new JwtService(), new ConfigService({ ...process.env, SALT_ROUNDS: Number(process.env.SALT_ROUNDS || 10), OTP_TTL_SECONDS: Number(process.env.OTP_TTL_SECONDS || 300) }), { send: async () => {} },
  { sendVerificationCode: async (email, code) => delivered.set(email, code), sendWelcome: async () => {} }, { accountCompleted: async () => {} });
const expectStatus = async (promise, status) => { let caught; try { await promise; } catch (err) { caught = err; } if (!caught?.getStatus) console.error(caught?.message); assert.equal(caught?.getStatus?.(), status); };
const guard = new AuthGuard(new Reflector(), prisma);
const requestContext = (id, path, method = 'GET') => ({ getHandler: () => ({}), getClass: () => ({}), switchToHttp: () => ({ getRequest: () => ({ user: { id, roles: ['player'] }, originalUrl: path, method, headers: {} }) }) });
(async () => {
  for (let i = 0; i < 3; i++) created.push(await prisma.user.create({ data: { name: `QA Guest ${i}`, isGuest: true, roles: ['player'], avatarConfig: { kitColor: '#00ff00' } } }));
  squad = await prisma.squad.create({ data: { members: { create: [{ userId: created[0].id }, { userId: created[1].id, isLeader: true }] } } });
  const email = `${prefix}@example.invalid`;
  const results = await Promise.allSettled([service.requestGuestEmailCode(created[0].id, email), service.requestGuestEmailCode(created[0].id, email)]);
  if (!results.some(r => r.status === 'fulfilled')) console.error(results.map(r => r.reason?.message));
  assert.equal(results.filter(r => r.status === 'fulfilled').length, 1, 'concurrent OTP requests send exactly one code');
  let otp = await prisma.otpCode.findFirst({ where: { userId: created[0].id }, orderBy: { createdAt: 'desc' } });
  assert.equal(otp.target, email); assert.ok(delivered.get(email));
  const payload = { name: 'QA Verified Guest', email, password: 'QaPassword123!', code: delivered.get(email) };
  const oldToken = await new JwtService().signAsync({ id: created[0].id, roles: ['player'] }, { secret: process.env.JWT_ACCESS_SECRET, expiresIn: '5m' });
  const http = (path, method = 'GET', body) => fetch('http://localhost:3000/api/v1' + path, { method, headers: { Authorization: 'Bearer ' + oldToken, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await http('/bookings/mine')).status, 403, 'HTTP confines a guest');
  assert.equal((await http('/auth/guest/complete', 'POST', { ...payload, code: payload.code === '9999' ? '8888' : '9999' })).status, 400, 'HTTP code errors do not expire the session');
  assert.equal((await http('/users/me')).status, 200, 'guest session survives an incorrect code');
  await expectStatus(service.completeGuest(created[1].id, payload), 400);
  await expectStatus(service.registerPlayerEmail(payload), 401);
  const wrong = payload.code === '9999' ? '8888' : '9999';
  await expectStatus(service.completeGuest(created[0].id, { ...payload, code: wrong }), 400);
  otp = await prisma.otpCode.findUnique({ where: { id: otp.id } }); assert.equal(otp.attempts, 2, 'wrong-code attempts commit');
  await expectStatus(guard.canActivate(requestContext(created[0].id, '/api/v1/bookings/mine')), 403);
  await expectStatus(guard.canActivate(requestContext(created[0].id, '/api/v1/auth/webauthn/register/options', 'POST')), 403);
  const promoted = await Promise.allSettled([service.completeGuest(created[0].id, payload), service.completeGuest(created[0].id, payload)]);
  assert.equal(promoted.filter(r => r.status === 'fulfilled').length, 1, 'the same identity is promoted exactly once');
  const user = await prisma.user.findUnique({ where: { id: created[0].id } });
  assert.equal(user.isGuest, false); assert.ok(user.emailVerifiedAt); assert.equal(user.email, email); assert.deepEqual(user.avatarConfig, { kitColor: '#00ff00' });
  assert.equal(await prisma.squadMember.count({ where: { userId: user.id, squadId: squad.id } }), 1, 'squad membership is retained');
  assert.equal(await guard.canActivate(requestContext(user.id, '/api/v1/bookings/mine')), true, 'old guest token identity now has verified access');
  assert.equal((await http('/users/me', 'PATCH', { email: 'changed@example.invalid' })).status, 400, 'profile cannot rewrite a verified email');
  assert.equal((await prisma.user.findUnique({ where: { id: user.id } })).email, email);
  const signedIn = await service.loginEmail({ email, password: payload.password }); assert.equal(signedIn.user.id, user.id, 'password sign-in returns the same profile');
  const exhaustedEmail = `${prefix}-lock@example.invalid`;
  await service.requestGuestEmailCode(created[2].id, exhaustedEmail);
  const right = delivered.get(exhaustedEmail); const incorrect = right === '9999' ? '8888' : '9999';
  for (let i = 0; i < 5; i++) await expectStatus(service.completeGuest(created[2].id, { ...payload, email: exhaustedEmail, code: incorrect }), 400);
  await expectStatus(service.completeGuest(created[2].id, { ...payload, email: exhaustedEmail, code: right }), 400);
  const locked = await prisma.user.findUnique({ where: { id: created[2].id } }); assert.equal(locked.isGuest, true); assert.equal(locked.email, null);
  console.log('PASS: real PostgreSQL OTP concurrency, atomic promotion, session binding, attempt lockout, guest confinement, membership preservation and subsequent password sign-in.');
})().catch(err => { console.error(err.message); process.exitCode = 1; }).finally(async () => {
  if (squad) await prisma.squad.delete({ where: { id: squad.id } });
  await prisma.user.deleteMany({ where: { id: { in: created.map(u => u.id) } } });
  await prisma.$disconnect();
});
